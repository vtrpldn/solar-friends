import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import path from 'node:path';
import {chromium} from 'playwright';
import {serve} from './serve.mjs';
import {createWeekend,chooseCamp,PROJECTS,requiredLoads,save,restore} from '../web/v02/weekend/simulation.js';
import {syncInfrastructure} from '../web/v02/weekend/infrastructure.js';
import {STORY_SAVE} from '../web/v02/weekend/modes.js';
const s=createWeekend(42);chooseCamp(s,'entrance');
s.rainSeen=s.rainResolved=true;s.wood=30;
Object.assign(s.materials,{planks:20,hardware:10,wheel_kit:2,bamboo:8,tool_heads:3,'carpentry-tools':1,'garden-tools':1,repair_supplies:3});
s.equipment={wear:{'garden-tools':900},loans:{},soapLeft:0};
for(const [key,x,z] of [['supply-5',40,39],['supply-5',44,39],['workshop',48,39]]) {
 s.projects.push({id:s.nextId++,key,x,z,work:PROJECTS[key].work,delivered:requiredLoads(key)});
}
syncInfrastructure(s,PROJECTS);
s.view={speed:1,paused:true,position:[20,35,20],target:[1,2,3],zoom:1};
assert(restore(save(s)),'browser fixture must be a valid saved village');
const directory=process.env.SOLAR_EVIDENCE_DIR;
if(directory)await mkdir(directory,{recursive:true});
const server=await serve();let browser;
try {
 browser=await chromium.launch({headless:true,args:['--mute-audio',...(process.platform==='linux'?['--use-angle=swiftshader','--enable-unsafe-swiftshader']:[])]});
 const page=await browser.newPage({viewport:{width:1440,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(({key,snapshot})=>localStorage.setItem(key,snapshot),{key:STORY_SAVE,snapshot:save(s)});
 await page.goto(`http://127.0.0.1:${server.address().port}/v2/?mode=story`);
 await page.locator('[data-manage="crafting"]').first().click();
 const root=page.locator('#crafting-screen');
 await root.locator('.craft-entry').first().waitFor();
 assert.equal(await root.locator('.craft-entry').count(),4);
 await root.getByRole('button',{name:'Jobs · 0',exact:true}).click();
 assert(await root.getByRole('heading',{name:'Nothing underway',exact:true}).isVisible());
 await root.getByRole('button',{name:'Browse things to make',exact:true}).click();
 await page.waitForFunction(()=>[...document.querySelectorAll('#crafting-screen img')].every(i=>i.complete&&i.naturalWidth>0),null,{timeout:120000});
 for(const width of [1440,1280]) {
  await page.setViewportSize({width,height:width===1280?720:900});
  assert(await root.getByRole('button',{name:'Make this item',exact:true}).isVisible());
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  const rect=await root.locator('.craft-action').boundingBox();
  assert(rect.y+rect.height<=(width===1280?720:900),'primary action stays in viewport');
  if(directory)await page.screenshot({path:path.join(directory,`craft-make-${width}.png`)});
 }
 await root.locator('[data-craft-focus="entry-craft_wheelbarrow"]').click();
 await root.getByText('Skills & how it’s made',{exact:true}).click();
 await root.locator('.craft-detail-body').evaluate(el=>el.scrollTop=el.scrollHeight);
 const scroll=await root.locator('.craft-detail-body').evaluate(el=>el.scrollTop);
 await page.getByRole('button',{name:'Close management screen',exact:true}).click();
 await page.locator('[data-manage="crafting"]').first().click();
 assert.equal(await root.locator('.craft-entry[aria-pressed="true"] strong').innerText(),'Wheelbarrow');
 assert.equal(await root.locator('details').getAttribute('open'),'');
 assert(Math.abs(await root.locator('.craft-detail-body').evaluate(el=>el.scrollTop)-scroll)<2,'detail scroll survives reopening');
 await root.getByRole('button',{name:'Make this item',exact:true}).click();
 assert.equal(await root.getByRole('button',{name:'Jobs · 1',exact:true}).getAttribute('aria-pressed'),'true');
 assert((await root.innerText()).includes('Materials reserved'));
 assert.equal(await root.locator('.craft-entry[aria-pressed="true"] strong').innerText(),'Wheelbarrow');
 await root.getByRole('button',{name:'Make',exact:true}).click();
 await root.locator('[data-craft-focus="entry-craft_garden-tools"]').click();
 const select=root.getByLabel('Workspace',{exact:true});
 await select.waitFor();
 const options=await select.locator('option').evaluateAll(options=>options.map(o=>o.value));
 await select.focus();
 await select.selectOption(options[1]);
 assert.equal(await select.evaluate(el=>el===document.activeElement),true,'workspace focus survives redraw');
 await root.getByRole('button',{name:'Make this item',exact:true}).click();
 await root.getByRole('button',{name:'Move unfinished job',exact:true}).click();
 assert((await root.innerText()).includes('Job moved'));
 if(directory)await page.screenshot({path:path.join(directory,'craft-jobs-1280.png')});
 await root.getByRole('button',{name:'Repair',exact:true}).click();
 assert.equal(await root.locator('.craft-entry').first().locator('strong').innerText(),'Garden tools');
 assert((await root.innerText()).includes('Needs repair'));
 await root.locator('[data-craft-focus="entry-repair_carpentry-tools"]').click();
 assert((await root.innerText()).includes('No repair needed'));
 assert(await root.getByRole('button',{name:'Start repair',exact:true}).isDisabled());
 await root.locator('[data-craft-focus="entry-repair_garden-tools"]').click();
 if(directory)await page.screenshot({path:path.join(directory,'craft-repair-1280.png')});
 await root.getByRole('button',{name:'Start repair',exact:true}).click();
 assert.equal(await root.getByRole('button',{name:'Jobs · 3',exact:true}).getAttribute('aria-pressed'),'true');
 assert((await root.innerText()).includes('REPAIR'));
 await root.getByRole('button',{name:'Repair',exact:true}).click();
 assert((await root.innerText()).includes('Repair in progress'));
 assert(await root.getByRole('button',{name:'Start repair',exact:true}).isDisabled());
 // Keyboard activation changes sections and Escape closes the modal.
 await root.getByRole('button',{name:'Make',exact:true}).focus();
 await page.keyboard.press('Enter');
 assert.equal(await root.getByRole('button',{name:'Make',exact:true}).getAttribute('aria-pressed'),'true');
 await page.keyboard.press('Escape');
 assert(!await page.locator('#management').isVisible());
 await page.reload();
 await page.locator('[data-manage="crafting"]').first().click();
 assert.equal(await root.getByRole('button',{name:'Make',exact:true}).getAttribute('aria-pressed'),'true','newly loaded village starts with fresh UI choices');
 assert.deepEqual(errors,[]);
 console.log('PASS crafting desktop: item browsing, illustrated details, repair states, queue-to-jobs, workspace choice and transfer, persistent selection/scroll/focus, keyboard and viewport checks.');
} finally {await browser?.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
