import assert from 'node:assert/strict';
import {BIOLOGY,GAME_DAY,biologicalStep,growthRate,harvestOutput,beginBiology} from '../web/v02/weekend/biological-production.js';
import {PROJECTS,PROCESSES,queueProduction,save,restore} from '../web/v02/weekend/simulation.js';
import {syncInfrastructure} from '../web/v02/weekend/infrastructure.js';
import {village,advance} from './fixtures.mjs';
const {s}=village();
const p={id:s.nextId++,key:'garden',x:s.stock.x+3,z:s.stock.z+3,work:PROJECTS.garden.work,delivered:0};s.projects.push(p);s.materials.seedlings=2;
const sys=syncInfrastructure(s,PROJECTS);sys.nodes[p.id].water[0]=12;
assert.equal(queueProduction(s,p.id,'vegetables'),'');
advance(s,{seconds:800,until:()=>s.operations[0].planted});
const op=s.operations[0];assert(op.planted,'residents actually plant before growth starts');assert.equal(op.phase,'growing');
assert(!s.people.some(r=>r.operation===op.id),'growth does not occupy a resident');
assert(restore(save(s)),'growing save restores');
const a={time:0,operations:[{recipe:'greenhouse',phase:'growing',growthRemaining:40*GAME_DAY,planted:true}]};
for(let day=0;day<40;day++){a.time+=GAME_DAY;biologicalStep(a,GAME_DAY);}
assert.equal(a.operations[0].phase,'process');assert.equal(a.operations[0].ripeAt,40*GAME_DAY);
assert.equal(harvestOutput({time:45*GAME_DAY},a.operations[0],PROCESSES.greenhouse).food,48);
assert.equal(harvestOutput({time:50.5*GAME_DAY},a.operations[0],PROCESSES.greenhouse).food,24);
assert.equal(harvestOutput({time:54*GAME_DAY},a.operations[0],PROCESSES.greenhouse).food,0);
assert(BIOLOGY.wood.days>BIOLOGY.bamboo.days&&BIOLOGY.bamboo.days>BIOLOGY.vegetables.days);
assert(growthRate({time:200*GAME_DAY,worldSettings:{biome:'caatinga'}},'vegetables')<1);
const bad=JSON.parse(save(s));bad.operations[0].growthRemaining=-1;assert.equal(restore(JSON.stringify(bad)),null);
const worker={operation:1};assert.equal(beginBiology({mode:'sandbox'}, {recipe:'vegetables'},worker),false);
console.log('PASS resident planting, autonomous calendar growth, seasonal slowdown, gradual field loss, save validation and sandbox');
const drought={time:0,rain:false,projects:[{id:1,soilMoisture:0,soilFertility:1}],operations:[{site:1,recipe:'vegetables',phase:'growing',growthRemaining:45*GAME_DAY,planted:true}]};
biologicalStep(drought,100,()=>false);assert.equal(drought.operations[0].growthRemaining,45*GAME_DAY,'dry soil stops growth');
let liters=0;for(let i=0;i<3200;i++)biologicalStep(drought,1,(_s,_id,n)=>{liters+=n;return true;});
assert(liters>0&&liters<=80.00001,'irrigation includes 2 mm/day refill and stops above the soil moisture target');assert(drought.operations[0].growthRemaining<45*GAME_DAY,'water resumes growth');
drought.rain=true;liters=0;biologicalStep(drought,100,()=>{liters++;return true;});assert.equal(liters,0,'rain replaces irrigation outdoors');
console.log('PASS dry-soil stall, continuing irrigation demand, recovery and rain substitution');
const orchard={id:1};const planting={time:0,projects:[orchard]},fruit={site:1,recipe:'fruit'};
assert(beginBiology(planting,fruit,{}));assert.equal(fruit.growthRemaining,730*GAME_DAY,'new orchard has a juvenile establishment period');
const repeat={site:1,recipe:'fruit'};assert(beginBiology(planting,repeat,{}));assert.equal(repeat.growthRemaining,120*GAME_DAY,'establishment does not recur for mature trees');
const {s:timber}=village({seed:44,fast:false});const stand={id:timber.nextId++,key:'supply-0',x:timber.stock.x+4,z:timber.stock.z+4,work:PROJECTS['supply-0'].work,delivered:0,harvestCount:1};timber.projects.push(stand);syncInfrastructure(timber,PROJECTS);
assert.match(queueProduction(timber,stand.id,'wood'),/tree_starts/);timber.materials.tree_starts=4;assert.equal(queueProduction(timber,stand.id,'wood'),'');assert.equal(timber.materials.tree_starts,0);assert(restore(save(timber)));
console.log('PASS juvenile orchard, mature repeat cycle and paid timber replanting inputs');

// Trees tolerate a short dry spell; prolonged drought still reduces the harvest.
const dryStand={time:0,rain:false,projects:[{id:1,soilMoisture:0,soilFertility:1,irrigationPolicy:'rainfed'}],operations:[{site:1,recipe:'wood',phase:'growing',growthRemaining:BIOLOGY.wood.days*GAME_DAY,planted:true}]};
for(let day=0;day<7;day++)biologicalStep(dryStand,GAME_DAY,()=>false);
assert.equal(dryStand.operations[0].phase,'growing');
assert.equal(dryStand.operations[0].droughtDamage,0,'a one-week dry spell does not kill timber');
for(let day=7;day<44;day++)biologicalStep(dryStand,GAME_DAY,()=>false);
assert.equal(dryStand.operations[0].droughtDamage,.5);
assert.equal(harvestOutput({time:0},{...dryStand.operations[0],ripeAt:0},PROCESSES.wood).logs,24);
for(let day=44;day<74;day++)biologicalStep(dryStand,GAME_DAY,()=>false);
assert.equal(dryStand.operations[0].phase,'process');
assert.equal(harvestOutput(dryStand,dryStand.operations[0],PROCESSES.wood).logs,0);
const legacy=JSON.parse(save(timber));legacy.operations[0].input.tree_starts=2;
assert(restore(JSON.stringify(legacy)),'already-paid two-seedling jobs from older saves remain valid');
console.log('PASS timber drought tolerance, prolonged loss, failed harvest and legacy replant saves');
