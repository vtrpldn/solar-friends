import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import init,{Game} from '../web/pkg/solar_friends.js';
await init({module_or_path:await readFile(new URL('../web/pkg/solar_friends_bg.wasm',import.meta.url))});
const g=new Game();
g.start_mode('sandbox');
const quote=(...p)=>JSON.parse(g.route_quote(...p));
const original=g.snapshot();
const open=quote(3,3,13,3);
assert.equal(open.model,'planned_haul');
assert.equal(open.blocker,null);
assert.equal(open.route.distance,10);
assert.equal(g.snapshot(),original,'Route inspection does not spend time, stock, or money');
for(let x=3;x<=13;x++)assert.equal(g.toggle_road(x,3),'ok');
const paved=quote(3,3,13,3);
assert.equal(paved.route.distance,open.route.distance);
assert(Math.abs(paved.route.minutes/open.route.minutes-.6)<.001,'Roads reduce planned transport effort');
const checkpoint=g.snapshot(),restored=new Game();
assert(restored.restore(checkpoint));
assert.deepEqual(JSON.parse(restored.route_quote(3,3,13,3)),paved,'Reload preserves route and prices');
for(let x=3;x<=13;x++)assert.equal(g.toggle_road(x,3),'ok');
assert.deepEqual(quote(3,3,13,3),open,'Removing the road immediately restores the unpaved estimate');
assert.equal(g.place('home',8,8),'ok');
const detour=quote(4,8,12,8);
assert(detour.route.distance>8);
for(const p of detour.route.points)assert(p[0]<=6.3||p[0]>=8.7||p[1]<=6.3||p[1]>=8.7);
assert.equal(quote(4,8,8,8).route,null,'Foundation destinations are blocked');
assert.equal(quote(3,3,27,3).route,null,'No route crosses the river');
assert.equal(quote(NaN,3,4,4).route,null);
assert.equal(quote(3,3,Infinity,4).route,null);
assert.equal(quote(4,4,4,4).route.minutes,0);
assert.equal(g.place_source(0,16,5),'ok');
assert.equal(quote(16,5,20,5).route,null,'Material plots block their actual footprint');
assert(quote(12,5,20,5).route.distance>8);
const short=quote(3.1,3.1,3.2,3.2);
assert(short.route.distance<.15,'Nearby fractional approaches do not detour to a grid centre');
const stable=g.snapshot();
for(let n=0;n<10;n++)assert.deepEqual(quote(4,8,12,8),detour);
assert.equal(g.snapshot(),stable,'Repeated and rejected quotes remain read-only');
g.free();restored.free();
console.log('PASS: deterministic planned transport routes, road costs, foundation and source detours, inaccessible endpoints, reloads and read-only public queries. Resident hauling remains a later integration.');
