// Compile traced architectural constraints into deterministic texture meshes.
// Source PNGs remain untouched; day and night use the identical geometry.
import {writeFile,readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {buildingProjection,measuredAxes} from '../web/building-projection.js';
import {allBuildingArt,cameraCalibration} from '../web/building-art.js';
import {triangulate,area} from './lib/triangulate.mjs';
const meshes={};
for(const [key,m]of Object.entries(buildingProjection)){
 const art=allBuildingArt[key],size=m.size,height=size*(art.aspect||1);
 const source=[[0,0],[size,0],[size,height],[0,height]],constraints=[];
 const point=p=>{let i=source.findIndex(q=>Math.hypot(p[0]-q[0],p[1]-q[1])<.01);if(i<0){i=source.length;source.push(p);}return i;};
 const edge=(e,slope)=>{const a=point(e.slice(0,2)),b=point(e.slice(2));constraints.push([[a,0,-slope],[a,1,1],[b,0,slope],[b,1,-1]]);};
 for(const e of m.right)edge(e,.5);for(const e of m.left)edge(e,-.5);
 const upright=m.uprights||[m.upright];
 for(const [x,y,X,Y]of upright){const a=point([x,y]),b=point([X,Y]);constraints.push([[a,0,1],[b,0,-1]]);}
 for(const [peak,left,right]of m.gables||[]){const a=point(peak),b=point(left),c=point(right);constraints.push([[a,0,1],[b,0,-.5],[c,0,-.5]]);}
 if(m.equalPosts){
  const pairs=upright.map(e=>[point(e.slice(0,2)),point(e.slice(2))]);
  for(const [a,b]of pairs.slice(1)){const [c,d]=pairs[0];constraints.push([[b,1,1],[a,1,-1],[d,1,-1],[c,1,1]]);}
 }
 for(const e of m.partialUprights||[]){const a=point(e.slice(0,2)),b=point(e.slice(2));constraints.push([[a,0,1],[b,0,-1]]);}
 for(const [A,B,C,D]of m.parallelograms||[]){const [a,b,c,d]=[A,B,C,D].map(point);for(const axis of [0,1])constraints.push([[a,axis,1],[b,axis,-1],[c,axis,1],[d,axis,-1]]);}
 for(const [E,F]of m.spans||[]){const [a,b,c,d]=[E.slice(0,2),E.slice(2),F.slice(0,2),F.slice(2)].map(point);for(const axis of [0,1])constraints.push([[b,axis,1],[a,axis,-1],[d,axis,-1],[c,axis,1]]);}
 for(const band of m.postBands||[]){
  const e=band.axis,a=point(e.slice(0,2)),b=point(e.slice(2)),[left,right,top,bottom]=band.bounds;
  for(const x of [left,right])for(let j=0;j<=4;j++){
   const y=top+(bottom-top)*j/4,i=point([x,y]),t=(y-e[1])/(e[3]-e[1]);
   const horizontal=[[i,0,1],[a,0,-1]];horizontal.rhs=x-e[0];constraints.push(horizontal);
   constraints.push([[i,1,1],[a,1,-(1-t)],[b,1,-t]]);
  }
 }
 const {vertical,shear}=cameraCalibration({...art,axes:measuredAxes(key)});
 // Start with the previous camera's shape; project onto exact parallel axes.
 const target=source.map(([x,y])=>[x,(y-height*art.anchor)*vertical+(x-size/2)*shear+height*art.anchor]);
 const pins=[];
 for(const circle of m.circles||[]){
  const [cx,cy]=circle.center,center=[cx,(cy-height*art.anchor)*vertical+(cx-size/2)*shear+height*art.anchor];
  for(let j=0;j<8;j++){
   if(circle.hidden?.includes(j))continue;
   const angle=j*Math.PI/4,sourcePoint=[cx+Math.cos(angle)*circle.radius,cy+Math.sin(angle)*circle.ry],i=point(sourcePoint);
   const corrected=[center[0]+Math.cos(angle)*circle.radius,center[1]+Math.sin(angle)*circle.radius*.5];
   target[i]=[...corrected];pins.push([i,corrected]);
  }
 }
 for(let pass=0;pass<3000;pass++){
 for(const terms of constraints){
  const residual=terms.reduce((sum,[i,a,w])=>sum+target[i][a]*w,0)-(terms.rhs||0),norm=terms.reduce((sum,[,,w])=>sum+w*w,0);
  for(const [i,a,w]of terms)target[i][a]-=residual*w/norm;
 }
 for(const [i,p]of pins)target[i]=[...p];
 }
 if(m.targets)for(const [sourcePoint,targetPoint]of m.targets){const i=point(sourcePoint);target[i]=targetPoint;}
 for(const terms of constraints)assert(Math.abs(terms.reduce((sum,[i,a,w])=>sum+target[i][a]*w,0)-(terms.rhs||0))<1e-5,`${key}: conflicting geometry`);
 // Store local repair before the shared camera transform. Canvas gutters stay
 // fixed, while reviewed structural controls are exact in the final camera.
 for(const p of target)p[1]=(p[1]-height*art.anchor-(p[0]-size/2)*shear)/vertical+height*art.anchor;
 const triangles=triangulate(source);
 for(const t of triangles){assert(area(...t.map(i=>source[i]))*area(...t.map(i=>target[i]))>0,`${key}: folded texture triangle ${t}`);}
 const sourceArea=triangles.reduce((sum,t)=>sum+area(...t.map(i=>source[i]))/2,0);assert(Math.abs(sourceArea-size*height)<.001,`${key}: uncovered source pixels`);
 meshes[key]={size,height,source,target,triangles};
}
const output='// Generated by scripts/rectify-buildings.mjs from reviewed source landmarks.\nexport const buildingMeshes='+JSON.stringify(meshes)+';\n';
const file='web/building-mesh-data.js';
if(process.argv.includes('--check'))assert.equal(await readFile(file,'utf8'),output,'Recompile the projection meshes after changing source landmarks');else await writeFile(file,output);
console.log(`PASS: ${Object.keys(meshes).length} complete, non-folded architectural meshes with exact traced constraints.`);
