import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import init,{Game} from '../web/pkg/solar_friends.js';
import {EditorDocument} from '../web/editor/document.js';

await init({module_or_path:await readFile(new URL('../web/pkg/solar_friends_bg.wasm',import.meta.url))});
const game=new Game();
try{
  const initial=JSON.parse(game.scenario_template('sandbox'));
  const doc=new EditorDocument(initial);
  let changes=0;doc.addEventListener('change',()=>changes++);
  const external=doc.value;external.title='An accidental external edit';
  assert.equal(doc.value.title,initial.title,'Reading a draft cannot mutate it');
  const before=doc.checkpoint();
  assert.throws(()=>doc.transact('Failed move',draft=>{draft.start.buildings[0].x=10;throw Error('cancelled');}));
  assert.throws(()=>doc.transact('Invalid number',draft=>{draft.start.minutes=NaN;}));
  assert.deepEqual(doc.checkpoint(),before);assert.equal(changes,0,'Failed edits are atomic');
  doc.transact('Paint a road',draft=>draft.start.roads.push([28,31],[29,31],[30,31]));
  assert.equal(changes,1,'One complete brush stroke is one transaction');
  const saved=doc.checkpoint();doc.markSaved(saved);assert(!doc.dirty);
  doc.transact('Move the shed',draft=>{draft.start.buildings[0].x=26;draft.start.buildings[0].y=29;});
  assert(doc.dirty);doc.markSaved(saved);assert(doc.dirty,'A slow save cannot acknowledge a newer edit');
  assert(doc.undo());assert(!doc.dirty);assert(doc.canRedo);
  const reopened=EditorDocument.restore(doc.checkpoint());
  assert.deepEqual(reopened.value,doc.value);assert.equal(reopened.redoLabel,'Move the shed');
  assert(reopened.redo());assert.equal(reopened.value.start.buildings[0].x,26);
  assert(reopened.undo());
  reopened.transact('Rename the property',draft=>{draft.title='A place for our friends';});
  assert(!reopened.canRedo,'A new branch discards only obsolete redo actions');
  const journal=reopened.checkpoint(),broken=structuredClone(journal);
  const detached=reopened.checkpoint();detached.history.past.at(-1).changes[0].after.value='A changed external checkpoint';
  assert.deepEqual(reopened.checkpoint(),journal,'Changing a returned journal cannot change live history');
  reopened.markSaved(journal);assert(!reopened.dirty);
  assert.equal(reopened.markSaved(saved),false);assert(!reopened.dirty,'An older acknowledgement cannot undo a newer successful save');
  broken.history.past.at(-1).after='{}';
  const recovered=EditorDocument.restore(broken);
  assert(recovered.historyRecovered);assert.deepEqual(recovered.value,journal.definition);
  assert(!recovered.canUndo,'Corrupt history cannot substitute another draft');
  const linked=new EditorDocument(initial);
  linked.transact('Remove the starting store',draft=>{draft.start.buildings=draft.start.buildings.filter(b=>b.id!=='starting-warehouse');});
  const result=JSON.parse(game.validate_scenario(JSON.stringify(linked.value)));
  assert(!result.ok&&result.issues.some(i=>i.code==='missing_store'),'Deletion keeps a visible unresolved reference instead of retargeting supplies');
  assert(linked.undo());assert(JSON.parse(game.validate_scenario(JSON.stringify(linked.value))).ok);
  linked.transact('Reorder the cast buildings',draft=>draft.start.buildings.reverse());
  assert(JSON.parse(game.load_scenario(JSON.stringify(linked.value))).ok);
  const state=JSON.parse(game.snapshot()),storeId=state.village.scenario.buildings['starting-warehouse'];
  assert(state.village.logistics.stores.some(p=>p.owner.kind==='warehouse'&&p.owner.id===storeId&&p.items[16]===80),'Reordering preserves named ownership');
  const bounded=new EditorDocument(initial);
  for(let n=0;n<100;n++)bounded.transact('Rename',draft=>{draft.title='Property '+n;});
  const checkpoint=bounded.checkpoint();assert.equal(checkpoint.history.past.length,64);
  assert.equal(EditorDocument.restore(checkpoint).value.title,'Property 99');
  const branch=new EditorDocument(initial);
  branch.transact('Name the property',d=>{d.title='Recovered title';});
  branch.transact('Place a road',d=>{d.start.roads.push([31,31]);});
  branch.transact('Write the future',d=>{d.description='Future description';});branch.undo();
  const beforeFork=branch.checkpoint(),fork=EditorDocument.fork(beforeFork,'independent-recovery');
  const bound=d=>{assert.equal(d.id,'independent-recovery');assert.equal(d.map.id,'map-independent-recovery');};
  bound(fork.value);assert.equal(fork.undoLabel,'Place a road');assert.equal(fork.redoLabel,'Write the future');
  assert.equal(fork.value.title,'Recovered title');fork.undo();bound(fork.value);assert.deepEqual(fork.value.start.roads,initial.start.roads);
  fork.undo();bound(fork.value);assert.equal(fork.value.title,initial.title);
  fork.redo();fork.redo();fork.redo();bound(fork.value);assert.equal(fork.value.description,'Future description');
  assert.deepEqual(branch.checkpoint(),beforeFork);assert(JSON.parse(game.validate_scenario(JSON.stringify(fork.value))).ok);
  const damagedFork=structuredClone(beforeFork);damagedFork.history.past[0].after={};
  const safeFork=EditorDocument.fork(damagedFork,'damaged-journal-copy');assert(safeFork.historyRecovered);assert.equal(safeFork.value.title,'Recovered title');assert(!safeFork.canUndo);
  const asynchronous=new EditorDocument(initial);
  for(let n=0;n<12;n++)asynchronous.transact('Name '+n,d=>{d.title='Name '+n;});
  asynchronous.undo();const captured=asynchronous.checkpoint();let yields=0;
  const prepared=await asynchronous.checkpointAsync({yieldControl:async()=>{
    if(++yields===1){asynchronous.redo();asynchronous.transact('During save',d=>{d.title='Newer unsaved edit';});}
  }});
  assert(yields>=4);assert.deepEqual(prepared,captured,'A yielding checkpoint owns one exact revision, including the captured redo branch');
  asynchronous.markSaved(prepared);assert(asynchronous.dirty,'Saving an older prepared revision must not acknowledge newer edits');
  prepared.history.past[0].label='External mutation';assert.equal(asynchronous.checkpoint().history.past[0].label,'Name 0');
  const beforeFailure=asynchronous.checkpoint();
  await assert.rejects(asynchronous.checkpointAsync({yieldControl:()=>Promise.reject(Error('Interrupted preparation'))}),/Interrupted preparation/);
  assert.deepEqual(asynchronous.checkpoint(),beforeFailure,'Failed preparation must preserve the complete live document');
  console.log('PASS: atomic editor transactions, complete-stroke undo/redo, history reopening/recovery, branching, save acknowledgements, stable references, and bounded history.');
}finally{game.free();}
