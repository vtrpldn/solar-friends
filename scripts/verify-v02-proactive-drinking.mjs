import assert from 'node:assert/strict';
import {ensureNeeds,chooseNeed,advanceNeed} from '../web/v02/weekend/resident-needs.js';
import {hydrationWarning} from '../web/v02/weekend/hydration.js';
const resident={id:'iara',name:'Iara',energy:100,action:'idle',x:0,z:0,walk:[]};
ensureNeeds(resident);
for(const key of Object.keys(resident.needs))resident.needs[key]=100;
const node={id:0,kind:'camp',enabled:true,x:0,z:0,water:[40,0,0,0],capacity:[40,60,120,80]};
const state={stage:'playing',time:0,stock:{x:0,z:0},people:[resident],materials:{},infrastructure:{nodes:{0:node},account:{waterUsed:0}}};
const api={serviceSpot:()=>({x:0,z:0}),route:()=>[{}],go:()=>true,groundSpot:()=>({x:0,z:0})};
resident.needs.hydration=60;
chooseNeed(state,resident,0,api);
assert.equal(resident.needTask?.kind,'hydration','Drink before reaching the thirst alert threshold');
assert.equal(hydrationWarning(state),'');
assert.equal(node.water[0],40,'Choosing a drink does not consume water remotely');
advanceNeed(state,resident,2,api);
assert.equal(resident.needs.hydration,80);
assert.equal(node.water[0],39.5);
assert.equal(state.infrastructure.account.waterUsed,.5);
state.time=4;
chooseNeed(state,resident,0,api);
assert.equal(resident.needTask,null,'Satisfied residents do not keep drinking');
resident.needs.hydration=20;node.water[0]=0;
chooseNeed(state,resident,0,api);
assert.match(hydrationWarning(state),/potable water/,'A real shortage still raises a warning');
node.water[0]=40;
chooseNeed(state,resident,0,{...api,route:()=>null});
assert.equal(resident.needTask,null);
assert.match(hydrationWarning(state),/reachable potable water/,'Unreachable water still raises a warning');
console.log('PASS proactive drinking, actual consumption, satisfied residents, shortages and unreachable water');
