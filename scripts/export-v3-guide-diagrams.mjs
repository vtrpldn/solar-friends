import { access, mkdir, readFile, writeFile } from "node:fs/promises";

const source = new URL("../web/v02/weekend/guide/", import.meta.url);
const target = new URL("../bevy-v3/src/village/", import.meta.url);
const topics = JSON.parse(await readFile(new URL("topics.json", source), "utf8"));
const entries = topics.map(({ id, title }) =>
  `        ${JSON.stringify(title)} => Some(load_embedded_asset!(assets, "guide_diagrams/${id}.png")),`).join("\n");
const registrations = topics.map(({ id }) =>
  `    embedded_asset!(app, "guide_diagrams/${id}.png");`).join("\n");
const registry = `// Generated by scripts/export-v3-guide-diagrams.mjs.
use bevy::{
    asset::{embedded_asset, load_embedded_asset},
    prelude::*,
};

pub(super) fn install(app: &mut App) {
${registrations}
}

#[rustfmt::skip]
pub(super) fn load(assets: &AssetServer, title: &str) -> Option<Handle<Image>> {
    match title {
${entries}
        _ => None,
    }
}
`;

const registryPath = new URL("guide_diagrams.rs", target);
if (process.argv.includes("--check")) {
  const chapters = JSON.parse(await readFile(new URL("../bevy-v3/data/guide.json", import.meta.url), "utf8"));
  const titles = topics.map(({ title }) => title);
  if (JSON.stringify(chapters.map(({ title }) => title)) !== JSON.stringify(titles)) {
    throw new Error("Bevy guide chapter titles or order differ from V2.");
  }
  // rustfmt can wrap the registration macros without changing their arguments.
  const tokens = text => text.match(/"(?:\\.|[^"\\])*"|\S/g).join("");
  if (tokens(await readFile(registryPath, "utf8")) !== tokens(registry)) {
    throw new Error("Bevy guide diagram registry differs from V2. Run node scripts/export-v3-guide-diagrams.mjs.");
  }
  for (const { id } of topics) {
    await access(new URL(`guide_diagrams/${id}.png`, target));
  }
} else {
  const { chromium } = await import("playwright");
  await mkdir(new URL("guide_diagrams/", target), { recursive: true });

  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } });
    for (const { id } of topics) {
      const svg = await readFile(new URL(`${id}.svg`, source));
      await page.setContent(`<body style="margin:0"><img style="display:block;max-width:1600px;max-height:1200px" src="data:image/svg+xml;base64,${svg.toString("base64")}"></body>`);
      await page.locator("img").evaluate(image => image.decode());
      await page.locator("img").screenshot({
        path: new URL(`guide_diagrams/${id}.png`, target).pathname,
        omitBackground: true,
      });
    }
  } finally {
    await browser.close();
  }
  await writeFile(registryPath, registry);
}
