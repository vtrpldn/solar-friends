import assert from 'node:assert/strict';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import init,{Game} from '../web/pkg/solar_friends.js';
import {makeScenario} from '../web/dev/scenarios.js';
import {weatherConditions} from '../web/weather.js';
import {weatherSummary} from '../web/climate-ui.js';
await init({module_or_path:await readFile(new URL('../web/pkg/solar_friends_bg.wasm',import.meta.url))});
const output='artifacts/climate';await mkdir(output,{recursive:true});
const game=new Game(),snap=()=>JSON.parse(game.snapshot()),fresh=snap();
assert.equal(fresh.village.climate.enabled,true);
assert(game.restore(await readFile(new URL('../web/artwork/village-preview.json',import.meta.url),'utf8')));
const established=snap(),untouched=JSON.stringify({fresh,established}),results=[];
for(const name of ['climate-wet','climate-dry']){
  const authored=makeScenario(name,fresh,established);
  assert.equal(JSON.stringify({fresh,established}),untouched,'Weather fixtures preserve their source villages');
  assert(game.restore(JSON.stringify(authored)));
  const before=snap(),weather=before.environment.weather,wet=name==='climate-wet';
  assert.equal(weather.enabled,true);assert.equal(weather.current.raining,wet);assert.equal(weather.forecast[0].season,wet?'wet':'dry');
  assert.equal(weather.forecast.length,7);
  const exact=game.snapshot(),forecast=game.weather_report();
  for(let i=0;i<10;i++)assert.equal(game.weather_report(),forecast);
  assert.equal(game.snapshot(),exact,'Inspecting the forecast is read-only');
  const copy=new Game();assert(copy.restore(exact));assert.equal(copy.snapshot(),exact);assert.equal(copy.weather_report(),forecast);copy.free();
  assert.equal(Boolean(weatherConditions(before.environment,before.village.minutes).rain),wet);
  assert.match(weatherSummary(weather,before.village.minutes),wet?/Rain until/:/Clear today/);
  const received=before.village.water_supply.received[0];
  game.tick(.25);const after=snap();
  assert(wet?after.village.water_supply.received[0]>received:after.village.water_supply.received[0]===received,'Only actual rain adds water to these cisterns');
  assert(JSON.parse(game.simulation_report()).materials.every(m=>m.difference===0));
  const water=JSON.parse(game.water_report());for(let i=0;i<4;i++)assert(Math.abs(water.opening[i]+water.received[i]-water.consumed[i]-water.present[i])<.001);
  const saved=game.snapshot();assert(game.restore(saved));assert.equal(game.snapshot(),saved);
  await writeFile(output+'/'+name+'.json',saved);
  results.push({name,day:1+Math.floor(before.village.minutes/1440),weather:weather.current,river_generation:before.environment.power.hydro_generation,solar_generation:before.environment.power.solar_generation,captured:after.village.water_supply.received[0]-received});
}
assert(results[0].river_generation>results[1].river_generation,'Wet and dry scenes use the same river generator with different actual flow');
assert(results[0].solar_generation<results[1].solar_generation,'Seeded cloud cover reduces actual solar output');
game.start_mode('sandbox');assert.equal(snap().village.climate.enabled,false);assert(game.set_seasons_enabled(true));
const selected=game.snapshot();assert(game.restore(selected));assert.equal(game.snapshot(),selected);assert(game.set_seasons_enabled(false));
await writeFile(output+'/sandbox-seasons.json',selected);
await writeFile(output+'/report.json',JSON.stringify({passed:true,results},null,2));game.free();
console.log('PASS: saved native forecasts, actual seasonal rain/solar/river conditions, accounted cistern collection, protected scene sources, matching visual weather and optional Sandbox seasons.');
