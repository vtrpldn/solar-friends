import assert from 'node:assert/strict';
import {createSandbox,PROJECTS,productionBlocker,queueProduction,buildingOperatingStatus} from '../web/v02/weekend/simulation.js';
import {syncInfrastructure} from '../web/v02/weekend/infrastructure.js';
const s=createSandbox(42);s.mode='story';
const p={id:s.nextId++,key:'supply-5',x:35,z:32,work:0};s.projects.push(p);
assert.equal(buildingOperatingStatus(s,p).state,'Under construction');
assert.match(productionBlocker(s,p.id,'craft_produce-crates'),/completed/);
p.work=PROJECTS[p.key].work;syncInfrastructure(s,PROJECTS);
s.materials['carpentry-tools']=1;s.materials.planks=0;
const before=JSON.stringify(s.materials);
assert.match(productionBlocker(s,p.id,'craft_produce-crates'),/Missing/);
assert.match(queueProduction(s,p.id,'craft_produce-crates'),/Missing/);
assert.equal(JSON.stringify(s.materials),before);
s.materials.planks=100;s.materials.hardware=100;
assert.equal(productionBlocker(s,p.id,'craft_produce-crates'),'');
assert.equal(queueProduction(s,p.id,'craft_produce-crates'),'');
assert.match(productionBlocker(s,p.id,'craft_produce-crates'),/already has a job/);
assert.equal(buildingOperatingStatus(s,p).state,'Waiting for a resident');
const op=s.operations.find(o=>o.site===p.id&&!o.done),r=s.people[0];
r.operation=op.id;r.needTask=null;r.tentPhase=null;r.energy=100;r.action='produce';
assert.equal(buildingOperatingStatus(s,p).state,'Working');
r.action='blocked';op.status='Waiting for usable water';
assert.equal(buildingOperatingStatus(s,p).reason,'Waiting for usable water');
op.phase='return';assert.equal(buildingOperatingStatus(s,p).state,'Delivering');
op.done=true;p.readyAt=s.time+100;
assert.equal(buildingOperatingStatus(s,p).state,'Growing');
p.readyAt=0;assert.equal(buildingOperatingStatus(s,p).state,'Ready');
console.log('PASS building lifecycle, blockers, and failed-job material preservation');
