import assert from 'node:assert/strict';
import {createSandbox, plan, PROJECTS} from '../web/v02/weekend/simulation.js';
import {projectLabel, upgradeAction, undoRoadPlan} from '../web/v02/weekend/project-ui.js';
assert.equal(projectLabel({key:'road',id:42}, PROJECTS), `${PROJECTS.road.name} #42`);
const home = {id:4};
assert.deepEqual(upgradeAction(home, []), {label:'Install solar upgrade',disabled:false});
assert.equal(upgradeAction(home, [{site:4,recipe:'solar_upgrade',done:false}]).label, 'Solar upgrade queued');
assert.equal(upgradeAction({...home,solarUpgrade:true}, []).disabled, true);
const state = createSandbox(42);
const before = structuredClone(state);
assert.equal(plan(state,'road',50,50), '');
const entry = {before, after:JSON.stringify(state)};
assert.equal(undoRoadPlan(state,entry),true);
assert.deepEqual(state,before);
assert.equal(plan(state,'road',50,50),'');
const changed = {before,after:JSON.stringify(state)};
state.time++;
const preserved = structuredClone(state);
assert.equal(undoRoadPlan(state,changed),false);
assert.deepEqual(state,preserved);
console.log('Project labels, upgrade states and guarded road undo passed.');
