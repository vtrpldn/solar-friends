import assert from 'node:assert/strict';
import {terraform} from '../web/v02/weekend/terraform.js';
import {elevationVertex, foundationPad} from '../web/v02/weekend/elevation.js';
import {createSandbox, save, restore, plan} from '../web/v02/weekend/simulation.js';
import {PARK_Z} from '../web/v02/weekend/road-layout.js';
const s=createSandbox(42), x=60,z=60;
const height=()=>elevationVertex(x,z,s.elevationSeed,s.terrainPads);
const original=height(),money=s.money,materials=JSON.stringify(s.materials),energy=s.people.map(r=>r.energy);
assert(terraform(s,x,z,'raise',8));assert(height()>original);
assert(terraform(s,x,z,'lower',8));assert(Math.abs(height()-original)<1e-8);
assert(terraform(s,x,z,'flatten',8,3));assert.equal(height(),3);
assert(terraform(s,x,z,'raise',4));const peak=height();
assert(terraform(s,x,z,'smooth',8));assert(height()<peak);
assert.equal(s.money,money);assert.equal(JSON.stringify(s.materials),materials);assert.deepEqual(s.people.map(r=>r.energy),energy);
const loaded=restore(save(s));assert(loaded);assert.equal(elevationVertex(x,z,42,loaded.terrainPads),height());
const before=JSON.stringify(s.terrainPads);terraform(s,1,PARK_Z,'raise',4);assert.equal(JSON.stringify(s.terrainPads),before);
const pad=foundationPad(62,62,2,2,42,s.terrainPads);s.terrainPads.push(pad);
const foundation=elevationVertex(62,62,42,s.terrainPads);terraform(s,62,62,'raise',12);
assert.equal(elevationVertex(62,62,42,s.terrainPads),foundation);
assert(!terraform(s,200,0,'raise',8));assert(!terraform(s,x,z,'flatten',8,NaN));
const bad=JSON.parse(save(s));bad.terrainPads.find(p=>p.terraform).vertices['60,60']=-1;
assert.equal(restore(JSON.stringify(bad)),null);
assert.equal(plan(loaded,'house',62,62),'','build on edited land');
assert(restore(save(loaded)));
console.log('PASS: raise/lower/flatten/smooth, zero costs, persistence, protected access/foundations, bounds and building on edited terrain.');
