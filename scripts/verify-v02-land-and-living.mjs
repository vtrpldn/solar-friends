import assert from 'node:assert/strict';
import {createWeekend,chooseCamp,PROJECTS,PROCESSES,plan,queueProduction,queueWater,queuePurification,tick,save,restore,requiredLoads} from '../web/v02/weekend/simulation.js';
import {ensureNaturalLand} from '../web/v02/weekend/natural-resources.js';
import {syncInfrastructure} from '../web/v02/weekend/infrastructure.js';
const advance=(s,until,limit=2400)=>{for(let i=0;i<limit*10&&!until();i++)tick(s,.1);assert(until(),'job must finish');};
const land=createWeekend(972341);ensureNaturalLand(land,PROJECTS);
assert(land.projects.filter(p=>p.key==='supply-3').length>=3);
assert(land.projects.filter(p=>PROJECTS[p.key].kind==='wild-tree').length>40);
const again=createWeekend(972341);ensureNaturalLand(again,PROJECTS);assert.deepEqual(land.projects,again.projects);
assert(restore(save(land)),'natural land restores during arrival');
chooseCamp(land,'shade');tick(land,.1);
assert(plan(land,'supply-3',45,45));
assert(restore(save(land)),'natural land restores during play');
const s=createWeekend();chooseCamp(s,'shade');s.rainSeen=true;s.rainResolved=true;
const node=syncInfrastructure(s,PROJECTS).nodes[0];node.water=[0,0,0,0];s.infrastructure.grid.enabled=false;
assert.equal(queueWater(s,-1,0,'fresh'),'River water is irrigation water; filter it before drinking.');
assert.equal(queueWater(s,-1,0,'irrigation'),'');
advance(s,()=>s.operations[0].done);
assert.equal(node.water[0],0);assert.equal(node.water[1],12);
assert.equal(queuePurification(s,0),'');advance(s,()=>s.operations[1].done);
assert(node.water[0]>0 && node.water[0]<=12);assert.equal(node.water[1],0);
assert(restore(save(s)),'purification save restores');
const tree={id:s.nextId++,key:'wild-jequitiba',x:37,z:32,work:1,delivered:0,natural:true};s.projects.push(tree);syncInfrastructure(s,PROJECTS);
assert.equal(queueProduction(s,tree.id,'fell_tree'),'');advance(s,()=>tree.felled && s.materials.logs===12);
assert(queueProduction(s,tree.id,'fell_tree'),'cannot cut same tree twice');
assert(restore(save(s)),'felled tree restores');
const bench={id:s.nextId++,key:'supply-5',x:38,z:36,work:PROJECTS['supply-5'].work,delivered:requiredLoads('supply-5')};s.projects.push(bench);syncInfrastructure(s,PROJECTS);
const wood=s.wood;assert.equal(queueProduction(s,bench.id,'saw_timber'),'');advance(s,()=>s.wood===wood+4);assert.equal(s.materials.logs,6);
assert.equal(queueProduction(s,bench.id,'saw_planks'),'');advance(s,()=>s.materials.planks===6);assert.equal(s.wood,wood+1);
const tired=createWeekend();chooseCamp(tired,'shade');tired.rainSeen=true;tired.rainResolved=true;
for(let i=0;i<18000;i++)tick(tired,.1);
assert(tired.people.some(r=>r.sleepUntil),'night schedules start sleep');
assert(tired.people.filter(r=>!r.sleepUntil).every(r=>r.energy<80),'awake residents are tired at 22:30');
assert(tired.people.some(r=>r.energy<60),'evening fatigue differs between residents');
const sleepEnds=tired.people.map(r=>r.sleepUntil);
advance(tired,()=>tired.time>Math.max(...sleepEnds)+5,1200);
assert(tired.people.every(r=>!r.sleepUntil),'residents finish one sleep per night');
console.log('PASS generated finite deposits, deterministic trees, save/load, raw-only hauling, manual purification, one-time felling, timber/planks and nighttime fatigue');
