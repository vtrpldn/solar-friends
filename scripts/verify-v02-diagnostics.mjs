import assert from 'node:assert/strict';
import {createDiagnostics,copyDiagnostics} from '../web/v02/weekend/diagnostics.js';
import {save,restore} from '../web/v02/weekend/simulation.js';
import {village} from './fixtures.mjs';
let clock=0;const diagnostics=createDiagnostics({now:()=>clock,limit:2});
const {s:state}=village({fast:false});
const before=save(state);diagnostics.observe(state);
assert.equal(save(state),before,'Observation leaves simulation unchanged');
state.people[0].walk=[{x:1,z:2}];clock=1000;diagnostics.observe(state);
state.people[0].walk[0].x=20;clock=2000;diagnostics.observe(state);
for(let i=0;i<35;i++)diagnostics.error('test',new Error(`error ${i}`));
const snapshot=save(state),report=JSON.parse(diagnostics.report(state,{paused:true,selectedSpeed:4}));
assert.equal(save(state),snapshot,'Export leaves simulation unchanged');
assert.equal(report.format,'solar-friends-diagnostics');
assert.equal(report.history.samples.length,2);assert.equal(report.history.errors.length,30);
assert.equal(report.history.samples[0].people[0].walk[0].x,1,'History remains detached from live paths');
assert.deepEqual(report.state,JSON.parse(snapshot));
assert(restore(JSON.stringify(report.state)),'Report contains a reloadable snapshot');
let copied;assert(await copyDiagnostics(snapshot,{clipboard:{writeText:async text=>{copied=text;}},document:{}}));assert.equal(copied,snapshot);
console.log('PASS bounded diagnostic history/errors, detached task paths, unchanged live simulation, reloadable state and clipboard payload.');
