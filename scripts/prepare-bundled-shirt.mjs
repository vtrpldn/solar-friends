// Package reviewed paint unchanged; public recipes must never supply source paths.
import assert from 'node:assert/strict';
import {readFile,readdir,mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root='assets/art-direction/character-prototype-v1';
const evidence=root+'/short-sleeve-relaxed-feed-motion-v1';
const out='web/art/characters/relaxed-shirt-v1';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const read=async path=>JSON.parse(await readFile(path));
const review=await read(evidence+'/motion-review-v1.json');
const verificationBytes=await readFile(evidence+'/verification-v1.json');
assert.equal(sha(verificationBytes),review.verificationSha256,'Reviewed integration evidence changed');
const verification=JSON.parse(verificationBytes);
assert.equal(verification.changed,384);assert.equal(verification.unchanged,0);
assert.equal(verification.clothedReturns,16);assert.equal(Object.keys(verification.inputs).length,48);
const garments=[],sources={},copies=new Map(),provenance=[];
for(const [collection,input]of Object.entries(verification.inputs)){
 assert(/^[a-z0-9-]+$/.test(collection));
 const folder=root+'/'+collection,files=await readdir(folder);
 const matching=async pattern=>{
  const found=[];
  for(const file of files.filter(file=>pattern.test(file))){const bytes=await readFile(folder+'/'+file);if(sha(bytes)===(file.endsWith('.png')?input.sourceSha256:input.registrationSha256))found.push({file,bytes});}
  assert(found.length>0,'Missing reviewed source/registration in '+collection);for(const entry of found)assert(entry.bytes.equals(found[0].bytes),'Conflicting reviewed bytes');return found.sort((a,b)=>a.file.localeCompare(b.file))[0];
 };
 const paint=await matching(/^candidate-v[1-9][0-9]?\.png$/);
 const registration=await matching(/^registrations-[a-z0-9-]+\.json$/);
 const rows=JSON.parse(registration.bytes);assert.equal(rows.length,1);
 const r=rows[0];assert.equal(r.part,'short-sleeve-v1');assert.equal(r.source.sha256,input.sourceSha256);
 assert(['base','idle','activities'].includes(r.sheet));assert(Number.isInteger(r.index)&&r.index>=0&&r.index<16);
 const file='source-'+input.sourceSha256+'.png';
 sources[file]={url:'/art/characters/relaxed-shirt-v1/'+file,sha256:input.sourceSha256};
 if(copies.has(file))assert(copies.get(file).equals(paint.bytes));else copies.set(file,paint.bytes);
 garments.push({file,registration:r});
 provenance.push({sheet:r.sheet,index:r.index,collection,source:paint.file,registration:registration.file,...input});
}
const order={base:0,idle:1,activities:2};
garments.sort((a,b)=>order[a.registration.sheet]-order[b.registration.sheet]||a.registration.index-b.registration.index);
assert.equal(new Set(garments.map(g=>g.registration.sheet+':'+g.registration.index)).size,48);
assert.equal(copies.size,verification.loadedGarmentImages);
const bytes=Buffer.from(JSON.stringify({schema:1,id:'relaxed-shirt-v1',sources,garments})+'\n');
assert(bytes.length<=4*1024*1024,'Keep garment registrations bounded');
async function frozen(path,bytes){let prior;try{prior=await readFile(path);}catch(error){if(error.code!=='ENOENT')throw error;}if(prior)assert(prior.equals(Buffer.from(bytes)),'Use a new frozen garment bundle revision: '+path);else await writeFile(path,bytes);}
await mkdir(out,{recursive:true});
for(const [file,bytes]of copies)await frozen(out+'/'+file,bytes);
await frozen(out+'/bundle-v1.json',bytes);
await frozen(out+'/provenance-v1.json',JSON.stringify({schema:1,verificationSha256:sha(verificationBytes),reviewSha256:sha(await readFile(evidence+'/motion-review-v1.json')),poses:provenance},null,2)+'\n');
await frozen('web/character-shirt-bundle-index.js','// Generated by scripts/prepare-bundled-shirt.mjs; unchanged reviewed paint.\nexport const bundledShirt=Object.freeze('+JSON.stringify({id:'relaxed-shirt-v1',url:'/art/characters/relaxed-shirt-v1/bundle-v1.json',sha256:sha(bytes),maximumBytes:4*1024*1024})+');\n');
console.log(JSON.stringify({poses:garments.length,uniqueSources:copies.size,registrationBytes:bytes.length,sourceBytes:[...copies.values()].reduce((n,b)=>n+b.length,0),sha256:sha(bytes)}));
