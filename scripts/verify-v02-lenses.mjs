import assert from 'node:assert/strict';
import {LENSES,lensData} from '../web/v02/weekend/lens-data.js';
import {createUtilitiesPreview} from '../web/v02/weekend/utilities-preview.js';
import {PROJECTS,requiredLoads} from '../web/v02/weekend/simulation.js';
import {ensureNaturalLand} from '../web/v02/weekend/natural-resources.js';
const s=createUtilitiesPreview(true,0);
s.landSeed=42;ensureNaturalLand(s,PROJECTS);
const build={id:s.nextId++,key:'house',x:50,z:50,work:0,delivered:0};s.projects.push(build);
const node=Object.values(s.infrastructure.nodes).find(n=>n.kind==='workshop');node.demand=1;node.power=0;
const waste=Object.values(s.infrastructure.nodes).find(n=>n.kind==='eco_toilet');waste.water[3]=waste.capacity[3];
s.people[0].needs={hunger:5};s.people[0].walk=[{x:32,z:34},{x:33,z:34}];
const snapshot=JSON.stringify(s);
for(const {id} of LENSES){const d=lensData(s,id);assert(Array.isArray(d.marks));for(const m of d.marks){assert(Number.isFinite(m.x)&&Number.isFinite(m.z));assert(m.detail&&!m.detail.includes('NaN'));}}
assert.equal(JSON.stringify(s),snapshot,'all lenses must be read-only');
assert(lensData(s,'power').marks.some(m=>m.tone==='bad'&&m.detail.includes('0% supplied')));
assert(lensData(s,'sanitation').marks.some(m=>m.tone==='bad'));
assert(lensData(s,'residents').marks.some(m=>m.detail.includes('hunger 5%')&&m.tone==='bad'));
assert.equal(lensData(s,'construction').marks.length,1);
build.delivered=requiredLoads(build.key);build.work=PROJECTS.house.work;
assert.equal(lensData(s,'construction').marks.length,0,'completed work disappears');
assert(lensData(s,'access').lines[0].points.length===3,'queued walking path includes resident origin');
const fresh=lensData(s,'water',{liquid:'fresh'}),sewage=lensData(s,'water',{liquid:'sewage'});
assert.notDeepEqual(fresh,sewage,'liquid filters change marks and pipes');
assert(lensData(s,'resources').marks.length>10);
const tree=s.projects.find(p=>PROJECTS[p.key].kind==='wild-tree');tree.felled=true;
assert(!lensData(s,'resources').marks.some(m=>m.projectId===tree.id));
assert(lensData(s,'ecology').marks.some(m=>m.projectId===tree.id&&m.tone==='muted'));
assert.notDeepEqual(lensData(s,'chains',{material:'food'}),lensData(s,'chains',{material:'stone'}));
assert.equal(LENSES.length,13);
console.log('PASS 13 read-only lenses, power shortages, full waste storage, urgent needs, construction completion, paths, filters and cleared trees');
